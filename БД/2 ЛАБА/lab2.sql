    DEFAULT TABLESPACE TS_GAA
    TEMPORARY TABLESPACE TS_GAA_TEMP
    PROFILE C##PF_GAACORE
    ACCOUNT UNLOCK;
    PASSWORD EXPIRE;
    
    GRANT CREATE SESSION TO C##GAACORE;
        

