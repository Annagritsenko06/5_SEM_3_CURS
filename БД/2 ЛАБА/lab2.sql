--4
CREATE ROLE C##R_GAACORE;
GRANT CONNECT TO  C##R_GAACORE;
GRANT CREATE TABLE, DROP ANY TABLE TO C##R_GAACORE;
GRANT CREATE VIEW, DROP ANY VIEW TO  C##R_GAACORE;
GRANT CREATE PROCEDURE, DROP ANY PROCEDURE TO  C##R_GAACORE;

--5
SELECT * FROM DBA_ROLES WHERE ROLE like 'C##R_GAACORE';

SELECT * 
FROM DBA_SYS_PRIVS,DBA_ROLES;


--6
CREATE PROFILE C##PF_GAACORE LIMIT
    PASSWORD_LIFE_TIME 180
    SESSIONS_PER_USER 3
    FAILED_LOGIN_ATTEMPTS 7
    PASSWORD_LOCK_TIME 1
    PASSWORD_REUSE_TIME 10
    PASSWORD_GRACE_TIME DEFAULT
    CONNECT_TIME 180
    IDLE_TIME 30;

--7
SELECT PROFILE FROM dba_profiles;

SELECT * FROM dba_profiles WHERE PROFILE = 'C##PF_GAACORE';

SELECT * FROM dba_profiles WHERE PROFILE = 'DEFAULT';

