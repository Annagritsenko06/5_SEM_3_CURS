--Таблицы

DROP TABLE SOURCE_TABLE;
DROP TABLE TARGET_TABLE;
DROP TABLE JOB_LOG;

CREATE TABLE SOURCE_TABLE (
    ID NUMBER PRIMARY KEY,
    DATA VARCHAR2(100)
);

CREATE TABLE TARGET_TABLE (
    ID NUMBER PRIMARY KEY,
    DATA VARCHAR2(100)
);

CREATE TABLE JOB_LOG (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_DATE DATE DEFAULT SYSDATE,
    STATUS VARCHAR2(20),
    ERROR_MESSAGE VARCHAR2(4000)
);

BEGIN 
FOR i IN 1..200 LOOP
INSERT INTO SOURCE_TABLE VALUES(i, 'DATA ' || i);
END LOOP;
END;

--Процедура выполняемая в job

CREATE OR REPLACE PROCEDURE COPY_AND_DELETE_DATA IS
BEGIN
    -- Копируем данные
    INSERT INTO TARGET_TABLE (ID, DATA)
    SELECT ID, DATA
    FROM SOURCE_TABLE
    WHERE ID < 100; -- Условие для копирования

    -- Удаляем данные
    DELETE FROM SOURCE_TABLE
    WHERE ID < 100;

    -- Логируем успешное выполнение
    INSERT INTO JOB_LOG (STATUS)
    VALUES ('SUCCESS');
EXCEPTION
    WHEN OTHERS THEN
        -- Логируем ошибку
        INSERT INTO JOB_LOG (STATUS, ERROR_MESSAGE)
        VALUES ('FAILED', 'Ошибка в ходе выполнения задачи');
        RAISE;
END;    



-- Удалить старый джоб
BEGIN DBMS_JOB.REMOVE(42); COMMIT; END;

-- Создать новый с немедленным запуском
DECLARE v_job_id NUMBER;
BEGIN
  DBMS_JOB.SUBMIT(
    job => v_job_id,
    what => 'COPY_AND_DELETE_DATA;',
    next_date => SYSDATE + 1/1440  -- через минуту
  );
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('New Job ID: ' || v_job_id);
END;
/

-- Принудительно запустить
BEGIN DBMS_JOB.RUN(43); END;
