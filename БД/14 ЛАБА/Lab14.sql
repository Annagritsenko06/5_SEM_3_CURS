        job_name        => 'COPY_AND_DELETE_JOB',
        job_type        => 'PLSQL_BLOCK',
        job_action      => 'BEGIN COPY_AND_DELETE_DATA; END;',
        start_date      => SYSDATE,
        repeat_interval => 'FREQ=WEEKLY; BYDAY=SUN; BYHOUR=2; BYMINUTE=0; BYSECOND=0',
        enabled         => TRUE,
        auto_drop       => FALSE,
        comments        => 'Weekly job to copy and delete data'
    );
END;

